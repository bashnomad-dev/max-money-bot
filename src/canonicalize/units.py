def canonicalize_unit(unit: str) -> str | None:
    """Привести единицу к канонической форме. None если не нашли — записываем как есть."""
    if not unit:
        return None
    key = unit.strip().lower().replace("ё", "е")
    return CANONICAL_UNITS.get(key)
